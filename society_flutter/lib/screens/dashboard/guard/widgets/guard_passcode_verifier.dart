import 'package:flutter/material.dart';
import '../../../../core/core.dart';
import '../../../../services/society_state.dart';

/// Instant 4-Digit Passcode / OTP Check-In for Gate Entry
class GuardPasscodeVerifier extends StatefulWidget {
  final SocietyState state;
  const GuardPasscodeVerifier({super.key, required this.state});

  @override
  State<GuardPasscodeVerifier> createState() => _GuardPasscodeVerifierState();
}

class _GuardPasscodeVerifierState extends State<GuardPasscodeVerifier> {
  final _controller = TextEditingController();
  bool _isVerifying = false;

  @override
  void dispose() {
    _controller.dispose();
    super.dispose();
  }

  Future<void> _handleVerify() async {
    final code = _controller.text.trim();
    if (code.length != 4) {
      AppSnackbar.showWarning(context, 'Please enter a valid 4-digit visitor PIN');
      return;
    }

    setState(() => _isVerifying = true);
    final success = await widget.state.guardVerifyPasscode(code);
    setState(() => _isVerifying = false);

    if (!mounted) return;

    if (success) {
      _controller.clear();
      AppSnackbar.showSuccess(
        context,
        'Gate Pass Verified! Boom barrier opened. Visitor marked INSIDE.',
      );
    } else {
      AppSnackbar.showError(
        context,
        'Invalid or expired passcode. Please verify with resident.',
      );
    }
  }

  @override
  Widget build(BuildContext context) {
    return AppCard(
      color: AppColors.successContainer,
      borderColor: AppColors.successBorder,
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            children: [
              Container(
                padding: const EdgeInsets.all(AppSpacing.xs),
                decoration: const BoxDecoration(
                  color: AppColors.successDark,
                  shape: BoxShape.circle,
                ),
                child: const Icon(Icons.pin_rounded, color: Colors.white, size: 16),
              ),
              AppSpacing.hGapSm,
              const Text(
                'QUICK PASSCODE / OTP CHECK-IN',
                style: TextStyle(
                  color: AppColors.successDark,
                  fontWeight: FontWeight.bold,
                  fontSize: 11,
                  letterSpacing: 0.5,
                ),
              ),
            ],
          ),
          AppSpacing.vGapSm,
          const Text(
            'Ask visitor for the 4-digit code generated by the resident.',
            style: TextStyle(fontSize: 12, color: Color(0xFF166534)),
          ),
          AppSpacing.vGapMd,
          Row(
            children: [
              Expanded(
                child: TextField(
                  controller: _controller,
                  keyboardType: TextInputType.number,
                  maxLength: 4,
                  textAlign: TextAlign.center,
                  style: const TextStyle(
                    fontSize: 22,
                    letterSpacing: 6,
                    fontWeight: FontWeight.bold,
                    color: AppColors.primaryNavy,
                  ),
                  decoration: InputDecoration(
                    counterText: '',
                    hintText: '• • • •',
                    hintStyle: const TextStyle(letterSpacing: 6, color: Colors.grey),
                    fillColor: Colors.white,
                    filled: true,
                    contentPadding: const EdgeInsets.symmetric(vertical: 12, horizontal: 14),
                    border: OutlineInputBorder(borderRadius: AppRadii.borderMd),
                  ),
                  onSubmitted: (_) => _handleVerify(),
                ),
              ),
              AppSpacing.hGapMd,
              AppButton.secondary(
                label: 'Verify & Open',
                icon: Icons.check_circle_rounded,
                isLoading: _isVerifying,
                onPressed: _handleVerify,
              ),
            ],
          ),
        ],
      ),
    );
  }
}
