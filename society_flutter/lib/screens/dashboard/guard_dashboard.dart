import 'package:flutter/material.dart';
import 'package:society_client/society_client.dart';
import '../../services/society_state.dart';
import '../../theme/app_theme.dart';

class GuardDashboard extends StatefulWidget {
  final SocietyState state;
  const GuardDashboard({super.key, required this.state});

  @override
  State<GuardDashboard> createState() => _GuardDashboardState();
}

class _GuardDashboardState extends State<GuardDashboard> {
  final _passcodeController = TextEditingController();
  int _selectedTab = 0; // 0: Inside, 1: Waiting Approval, 2: Expected Passes

  @override
  void dispose() {
    _passcodeController.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final state = widget.state;
    final insideVisitors = state.visitors.where((v) => v.status == VisitorStatus.inside).toList();
    final waitingVisitors = state.visitors.where((v) => v.status == VisitorStatus.waitingApproval).toList();
    final expectedVisitors = state.visitors.where((v) => v.status == VisitorStatus.expected).toList();

    return SingleChildScrollView(
      padding: const EdgeInsets.all(16),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          // Gate Banner
          Container(
            padding: const EdgeInsets.all(16),
            decoration: BoxDecoration(
              color: AppTheme.darkSlate,
              borderRadius: BorderRadius.circular(14),
            ),
            child: Row(
              children: [
                const CircleAvatar(
                  radius: 24,
                  backgroundColor: AppTheme.accentTeal,
                  child: Icon(Icons.security, color: Colors.white, size: 26),
                ),
                const SizedBox(width: 14),
                Expanded(
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      const Text(
                        'Main Security Gate 1',
                        style: TextStyle(
                          color: Colors.white,
                          fontWeight: FontWeight.bold,
                          fontSize: 17,
                        ),
                      ),
                      const SizedBox(height: 2),
                      Text(
                        'Duty Guard: Santosh Gawde • Campus Gate',
                        style: TextStyle(color: Colors.white.withValues(alpha: 0.75), fontSize: 13),
                      ),
                    ],
                  ),
                ),
                Container(
                  padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 4),
                  decoration: BoxDecoration(
                    color: AppTheme.successGreen,
                    borderRadius: BorderRadius.circular(12),
                  ),
                  child: const Text(
                    'GATE ACTIVE',
                    style: TextStyle(color: Colors.white, fontSize: 11, fontWeight: FontWeight.bold),
                  ),
                ),
              ],
            ),
          ),
          const SizedBox(height: 16),

          // Instant Passcode Verifier Card (For fast entry of deliveries/guests)
          Card(
            color: const Color(0xFFF0FDF4),
            shape: RoundedRectangleBorder(
              borderRadius: BorderRadius.circular(14),
              side: const BorderSide(color: Color(0xFF86EFAC)),
            ),
            child: Padding(
              padding: const EdgeInsets.all(16),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  const Row(
                    children: [
                      Icon(Icons.pin, color: AppTheme.successGreen),
                      SizedBox(width: 8),
                      Text(
                        'Quick Passcode / OTP Check-In',
                        style: TextStyle(fontWeight: FontWeight.bold, fontSize: 15, color: Color(0xFF14532D)),
                      ),
                    ],
                  ),
                  const SizedBox(height: 6),
                  const Text(
                    'Ask visitor for the 4-digit code generated by the resident.',
                    style: TextStyle(fontSize: 12, color: Color(0xFF166534)),
                  ),
                  const SizedBox(height: 12),
                  Row(
                    children: [
                      Expanded(
                        child: TextField(
                          controller: _passcodeController,
                          keyboardType: TextInputType.number,
                          maxLength: 4,
                          textAlign: TextAlign.center,
                          style: const TextStyle(
                            fontSize: 20,
                            letterSpacing: 4,
                            fontWeight: FontWeight.bold,
                          ),
                          decoration: InputDecoration(
                            counterText: '',
                            hintText: '• • • •',
                            hintStyle: const TextStyle(letterSpacing: 4),
                            fillColor: Colors.white,
                            contentPadding: const EdgeInsets.symmetric(vertical: 10, horizontal: 14),
                            border: OutlineInputBorder(borderRadius: BorderRadius.circular(10)),
                          ),
                        ),
                      ),
                      const SizedBox(width: 12),
                      ElevatedButton.icon(
                        icon: const Icon(Icons.check, size: 18),
                        label: const Text('Verify & Open Gate'),
                        style: ElevatedButton.styleFrom(
                          backgroundColor: AppTheme.successGreen,
                          padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 14),
                        ),
                        onPressed: () {
                          if (_passcodeController.text.isNotEmpty) {
                            final ok = state.guardVerifyPasscode(_passcodeController.text.trim());
                            if (ok) {
                              _passcodeController.clear();
                              ScaffoldMessenger.of(context).showSnackBar(
                                const SnackBar(
                                  backgroundColor: AppTheme.successGreen,
                                  content: Text('Passcode Verified! Entry Granted & Gate Opened.'),
                                ),
                              );
                            } else {
                              ScaffoldMessenger.of(context).showSnackBar(
                                const SnackBar(
                                  backgroundColor: AppTheme.dangerRed,
                                  content: Text('Invalid or Expired Passcode! Please register manually.'),
                                ),
                              );
                            }
                          }
                        },
                      ),
                    ],
                  ),
                ],
              ),
            ),
          ),
          const SizedBox(height: 16),

          // Big Record Visitor Button
          SizedBox(
            width: double.infinity,
            height: 50,
            child: ElevatedButton.icon(
              icon: const Icon(Icons.person_add_alt_1, size: 22),
              label: const Text(
                'New Visitor Check-In (Manual Entry)',
                style: TextStyle(fontSize: 15, fontWeight: FontWeight.bold),
              ),
              style: ElevatedButton.styleFrom(
                backgroundColor: AppTheme.primaryNavy,
              ),
              onPressed: () => _showNewVisitorModal(context),
            ),
          ),
          const SizedBox(height: 18),

          // Tab Filter Chips
          Row(
            children: [
              _buildFilterTab(
                index: 0,
                label: 'Inside Society',
                count: insideVisitors.length,
                color: AppTheme.successGreen,
              ),
              const SizedBox(width: 8),
              _buildFilterTab(
                index: 1,
                label: 'Pending Approval',
                count: waitingVisitors.length,
                color: AppTheme.dangerRed,
              ),
              const SizedBox(width: 8),
              _buildFilterTab(
                index: 2,
                label: 'Expected Passes',
                count: expectedVisitors.length,
                color: AppTheme.infoBlue,
              ),
            ],
          ),
          const SizedBox(height: 14),

          // Visitor List based on Tab
          if (_selectedTab == 0) ...[
            if (insideVisitors.isEmpty)
              const Center(
                child: Padding(
                  padding: EdgeInsets.all(32),
                  child: Text('No external visitors currently inside campus.'),
                ),
              )
            else
              ...insideVisitors.map((v) => _buildVisitorCard(v, isInside: true)),
          ] else if (_selectedTab == 1) ...[
            if (waitingVisitors.isEmpty)
              const Center(
                child: Padding(
                  padding: EdgeInsets.all(32),
                  child: Text('No visitor approval requests pending.'),
                ),
              )
            else
              ...waitingVisitors.map((v) => _buildVisitorCard(v, isWaiting: true)),
          ] else ...[
            if (expectedVisitors.isEmpty)
              const Center(
                child: Padding(
                  padding: EdgeInsets.all(32),
                  child: Text('No expected visitor passes at the moment.'),
                ),
              )
            else
              ...expectedVisitors.map((v) => _buildVisitorCard(v, isExpected: true)),
          ],
        ],
      ),
    );
  }

  Widget _buildFilterTab({
    required int index,
    required String label,
    required int count,
    required Color color,
  }) {
    final isSelected = _selectedTab == index;
    return Expanded(
      child: InkWell(
        onTap: () => setState(() => _selectedTab = index),
        borderRadius: BorderRadius.circular(10),
        child: Container(
          padding: const EdgeInsets.symmetric(vertical: 10, horizontal: 8),
          decoration: BoxDecoration(
            color: isSelected ? AppTheme.primaryNavy : Colors.white,
            borderRadius: BorderRadius.circular(10),
            border: Border.all(
              color: isSelected ? AppTheme.primaryNavy : AppTheme.borderLight,
            ),
          ),
          child: Column(
            children: [
              Text(
                count.toString(),
                style: TextStyle(
                  fontSize: 18,
                  fontWeight: FontWeight.bold,
                  color: isSelected ? Colors.white : color,
                ),
              ),
              const SizedBox(height: 2),
              Text(
                label,
                style: TextStyle(
                  fontSize: 11,
                  fontWeight: FontWeight.w600,
                  color: isSelected ? Colors.white.withValues(alpha: 0.9) : Colors.grey.shade700,
                ),
                textAlign: TextAlign.center,
                maxLines: 1,
              ),
            ],
          ),
        ),
      ),
    );
  }

  Widget _buildVisitorCard(
    VisitorEntry v, {
    bool isInside = false,
    bool isWaiting = false,
    bool isExpected = false,
  }) {
    return Card(
      margin: const EdgeInsets.only(bottom: 12),
      child: Padding(
        padding: const EdgeInsets.all(14),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Row(
              mainAxisAlignment: MainAxisAlignment.spaceBetween,
              children: [
                Expanded(
                  child: Text(
                    v.visitorName,
                    style: const TextStyle(fontWeight: FontWeight.bold, fontSize: 16),
                  ),
                ),
                Container(
                  padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 4),
                  decoration: BoxDecoration(
                    color: AppTheme.primaryNavy.withValues(alpha: 0.1),
                    borderRadius: BorderRadius.circular(8),
                  ),
                  child: Text(
                    'Flat ${v.flatNumber}',
                    style: const TextStyle(
                      fontWeight: FontWeight.bold,
                      color: AppTheme.primaryNavy,
                      fontSize: 13,
                    ),
                  ),
                ),
              ],
            ),
            const SizedBox(height: 6),
            Row(
              children: [
                Icon(Icons.phone, size: 14, color: Colors.grey.shade600),
                const SizedBox(width: 4),
                Text(v.phoneNumber, style: TextStyle(color: Colors.grey.shade700, fontSize: 13)),
                const SizedBox(width: 12),
                Icon(Icons.category, size: 14, color: Colors.grey.shade600),
                const SizedBox(width: 4),
                Text(v.purpose, style: TextStyle(color: Colors.grey.shade700, fontSize: 13)),
                if (v.vehicleNumber != null) ...[
                  const SizedBox(width: 12),
                  Icon(Icons.two_wheeler, size: 14, color: Colors.grey.shade600),
                  const SizedBox(width: 4),
                  Text(v.vehicleNumber!, style: TextStyle(color: Colors.grey.shade700, fontSize: 13)),
                ],
              ],
            ),
            if (isInside) ...[
              const SizedBox(height: 12),
              Row(
                mainAxisAlignment: MainAxisAlignment.spaceBetween,
                children: [
                  Text(
                    'Entered at ${v.checkInTime != null ? "${v.checkInTime!.hour}:${v.checkInTime!.minute.toString().padLeft(2, '0')}" : "Gate 1"}',
                    style: TextStyle(color: Colors.grey.shade600, fontSize: 12),
                  ),
                  ElevatedButton.icon(
                    icon: const Icon(Icons.exit_to_app, size: 16),
                    label: const Text('Mark Exit'),
                    style: ElevatedButton.styleFrom(
                      backgroundColor: AppTheme.dangerRed,
                      padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 8),
                    ),
                    onPressed: () {
                      widget.state.updateVisitorStatus(v.id!, VisitorStatus.exited);
                      ScaffoldMessenger.of(context).showSnackBar(
                        const SnackBar(content: Text('Visitor Marked as Exited!')),
                      );
                    },
                  ),
                ],
              ),
            ],
            if (isWaiting) ...[
              const SizedBox(height: 12),
              Row(
                mainAxisAlignment: MainAxisAlignment.spaceBetween,
                children: [
                  const Text(
                    'Awaiting Flat Owner Approval...',
                    style: TextStyle(color: AppTheme.dangerRed, fontWeight: FontWeight.bold, fontSize: 12),
                  ),
                  OutlinedButton(
                    onPressed: () {
                      widget.state.updateVisitorStatus(v.id!, VisitorStatus.inside);
                      ScaffoldMessenger.of(context).showSnackBar(
                        const SnackBar(content: Text('Entry Manually Approved by Security.')),
                      );
                    },
                    child: const Text('Guard Override Entry'),
                  ),
                ],
              ),
            ],
          ],
        ),
      ),
    );
  }

  void _showNewVisitorModal(BuildContext context) {
    final nameCtrl = TextEditingController();
    final phoneCtrl = TextEditingController();
    final flatCtrl = TextEditingController(text: 'A-304');
    final vehicleCtrl = TextEditingController();
    String purpose = 'Guest';

    showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      builder: (ctx) => Padding(
        padding: EdgeInsets.only(
          top: 20,
          left: 20,
          right: 20,
          bottom: MediaQuery.of(ctx).viewInsets.bottom + 20,
        ),
        child: SingleChildScrollView(
          child: Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              const Text(
                'Gate Visitor Registration',
                style: TextStyle(fontSize: 18, fontWeight: FontWeight.bold),
              ),
              const SizedBox(height: 14),
              TextField(
                controller: nameCtrl,
                decoration: const InputDecoration(labelText: 'Visitor Name'),
              ),
              const SizedBox(height: 12),
              TextField(
                controller: phoneCtrl,
                keyboardType: TextInputType.phone,
                decoration: const InputDecoration(labelText: 'Mobile Number'),
              ),
              const SizedBox(height: 12),
              Row(
                children: [
                  Expanded(
                    child: TextField(
                      controller: flatCtrl,
                      decoration: const InputDecoration(labelText: 'Flat Number (e.g. A-304)'),
                    ),
                  ),
                  const SizedBox(width: 12),
                  Expanded(
                    child: DropdownButtonFormField<String>(
                      initialValue: purpose,
                      decoration: const InputDecoration(labelText: 'Purpose'),
                      items: const [
                        DropdownMenuItem(value: 'Guest', child: Text('Guest')),
                        DropdownMenuItem(value: 'Delivery', child: Text('Delivery')),
                        DropdownMenuItem(value: 'Cab', child: Text('Cab')),
                        DropdownMenuItem(value: 'Service', child: Text('Service')),
                      ],
                      onChanged: (val) => purpose = val!,
                    ),
                  ),
                ],
              ),
              const SizedBox(height: 12),
              TextField(
                controller: vehicleCtrl,
                decoration: const InputDecoration(labelText: 'Vehicle Number (Optional)'),
              ),
              const SizedBox(height: 16),
              SizedBox(
                width: double.infinity,
                child: ElevatedButton.icon(
                  icon: const Icon(Icons.send),
                  label: const Text('Send Approval Notification to Flat'),
                  onPressed: () {
                    if (nameCtrl.text.isNotEmpty) {
                      widget.state.guardRecordEntry(
                        visitorName: nameCtrl.text,
                        phone: phoneCtrl.text.isEmpty ? '9811111111' : phoneCtrl.text,
                        flatNumber: flatCtrl.text,
                        purpose: purpose,
                        vehicle: vehicleCtrl.text.isEmpty ? null : vehicleCtrl.text,
                      );
                      Navigator.pop(ctx);
                      ScaffoldMessenger.of(context).showSnackBar(
                        const SnackBar(content: Text('Gate Entry Recorded! Bell sent to Resident.')),
                      );
                    }
                  },
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }
}
